from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Tuple

from counting_dataset.adapters.base import AdapterContext, DatasetAdapter
from counting_dataset.core.ids import make_ann_id, make_image_id, normalize_relpath
from counting_dataset.core.schema import (
    AnnType,
    ClassRecord,
    HBB,
    ImageRecord,
    InstanceAnnotationRecord,
    Point,
    SourceType,
    SplitType,
)


def _tile_number(tile_name: str) -> int:
    """'tile_33.jpg' -> 33"""
    stem = tile_name.rsplit(".", 1)[0]
    return int(stem.split("_", 1)[1])


class BirdsAdapter(DatasetAdapter):
    """
    Adapter for raw/birds/ using the original .tif images as the unit of analysis.

    Tile-local point annotations are translated to global image coordinates using
    the deterministic row-major tile layout from tile.py.  HBB pseudo-bboxes are
    loaded from a pre-computed cache (raw/birds/pseudo_bboxes_cache.json) and
    translated the same way.  Run generate_bird_bbox_cache.py once before building
    the index.

    Raw layout::

        raw/birds/
          _DSC5214.tif                  <- source image (sky scene)
          _DSC5295.tif                  <- source image (reeds scene)
          pseudo_bboxes_cache.json      <- generated by generate_bird_bbox_cache.py
          tiles/
            tiles_DSC5214/
              <batch_id>/
                tile_<N>.jpg
              labels/
                <batch_id>.json
            tiles_DSC5295/
              ...

    Tile numbering encodes position directly (row-major, stride = tile size):
        col = tile_num % tiles_per_row
        row = tile_num // tiles_per_row
        global_x = col * tile_w + local_x
        global_y = row * tile_h + local_y

    Tile sizes: DSC5214 → 200×200 px, DSC5295 → 160×160 px.

    * Unit of analysis: full .tif image (two images total).
    * One class: birds/bird.
    * scene ("sky" or "reeds") stored in image meta for meta_filter use.
    * Two annotation roles per labeled point:
      - POINT / role="instance" / source=ORIGINAL — ground-truth count.
      - HBB   / role="hbb"      / source=GENERATED — Otsu pseudo-bbox in global
        coords (emitted only when cache entry exists for the tile).
    """

    dataset = "birds"

    _TILE_SIZES: Dict[str, Tuple[int, int]] = {
        "tiles_DSC5214": (200, 200),
        "tiles_DSC5295": (160, 160),
    }
    _TIF_FILES: Dict[str, str] = {
        "tiles_DSC5214": "_DSC5214.tif",
        "tiles_DSC5295": "_DSC5295.tif",
    }
    _SOURCE_NAMES: Dict[str, str] = {
        "tiles_DSC5214": "sky",
        "tiles_DSC5295": "reeds",
    }

    def _dataset_root(self, ctx: AdapterContext) -> Path:
        return ctx.raw_root / "birds"

    def _tiles_root(self, ctx: AdapterContext) -> Path:
        return self._dataset_root(ctx) / "tiles"

    def _iter_src_dirs(self, ctx: AdapterContext) -> List[Path]:
        tiles_root = self._tiles_root(ctx)
        if not tiles_root.exists():
            return []
        return sorted(
            p for p in tiles_root.iterdir()
            if p.is_dir() and p.name in self._TIF_FILES
        )

    @staticmethod
    def _tif_dims(path: Path) -> Tuple[int, int]:
        try:
            from PIL import Image as _PIL
            with _PIL.open(path) as im:
                return im.size  # (width, height)
        except Exception:
            return 0, 0

    @staticmethod
    def _sorted_entries(data: Dict) -> List[Tuple[str, dict]]:
        return sorted(
            data.items(),
            key=lambda kv: _tile_number(kv[1]["filename"].split("/")[-1]),
        )

    def _load_bbox_cache(self, ctx: AdapterContext) -> Dict[str, List[List[float]]]:
        """Load pre-computed per-tile pseudo-bbox cache. Returns {} if absent."""
        cache_path = self._dataset_root(ctx) / "pseudo_bboxes_cache.json"
        if not cache_path.exists():
            return {}
        with cache_path.open("r", encoding="utf-8") as f:
            return json.load(f)

    def iter_classes(self, ctx: AdapterContext) -> Iterable[ClassRecord]:
        yield ClassRecord(
            class_key=f"{self.dataset}/bird",
            dataset=self.dataset,
            name="bird",
        )

    def iter_images(self, ctx: AdapterContext) -> Iterable[ImageRecord]:
        dataset_root = self._dataset_root(ctx)
        for src_dir in self._iter_src_dirs(ctx):
            tif_name = self._TIF_FILES[src_dir.name]
            tif_path = dataset_root / tif_name
            if not tif_path.exists():
                continue

            rel = normalize_relpath(tif_name)
            image_id = make_image_id(self.dataset, rel)
            w, h = self._tif_dims(tif_path)

            yield ImageRecord(
                image_id=image_id,
                path=str(tif_path),
                width=w,
                height=h,
                split=SplitType.UNSPECIFIED,
                dataset=self.dataset,
                original_relpath=rel,
                original_filename=tif_name,
                meta={"scene": self._SOURCE_NAMES.get(src_dir.name, src_dir.name)},
            )

    def iter_annotations(self, ctx: AdapterContext) -> Iterable[InstanceAnnotationRecord]:
        dataset_root = self._dataset_root(ctx)
        class_key = f"{self.dataset}/bird"
        bbox_cache = self._load_bbox_cache(ctx)

        for src_dir in self._iter_src_dirs(ctx):
            tif_name = self._TIF_FILES[src_dir.name]
            tif_path = dataset_root / tif_name
            if not tif_path.exists():
                continue

            rel = normalize_relpath(tif_name)
            image_id = make_image_id(self.dataset, rel)

            tile_w, tile_h = self._TILE_SIZES[src_dir.name]
            orig_w, _ = self._tif_dims(tif_path)
            if orig_w == 0:
                continue
            tiles_per_row = math.ceil(orig_w / tile_w)  # mirrors range(0, orig_w, tile_w)

            labels_dir = src_dir / "labels"
            if not labels_dir.is_dir():
                continue

            inst_idx = 0  # global per-image counter across all tiles

            for lf in sorted(labels_dir.glob("*.json"), key=lambda p: int(p.stem)):
                batch = int(lf.stem)
                with lf.open("r", encoding="utf-8") as f:
                    data: Dict = json.load(f)

                for _key, value in self._sorted_entries(data):
                    filename = value["filename"]
                    tile_name = filename.split("/")[-1]
                    regions = value.get("regions") or []
                    if not regions:
                        continue

                    tile_num = _tile_number(tile_name)
                    col = tile_num % tiles_per_row
                    row = tile_num // tiles_per_row
                    offset_x = col * tile_w
                    offset_y = row * tile_h

                    sorted_regions = sorted(
                        regions,
                        key=lambda r: (
                            r["shape_attributes"]["cx"],
                            r["shape_attributes"]["cy"],
                        ),
                    )

                    cache_key = f"{src_dir.name}/{batch}/{tile_name}"
                    tile_boxes: Optional[List[List[float]]] = bbox_cache.get(cache_key)

                    for local_idx, reg in enumerate(sorted_regions):
                        local_cx = float(reg["shape_attributes"]["cx"])
                        local_cy = float(reg["shape_attributes"]["cy"])
                        pt_geom = Point(
                            x=local_cx + offset_x,
                            y=local_cy + offset_y,
                        )

                        yield InstanceAnnotationRecord(
                            ann_id=make_ann_id(
                                image_id=image_id,
                                class_key=class_key,
                                ann_type=AnnType.POINT,
                                geometry=pt_geom,
                                source=SourceType.ORIGINAL,
                                instance_index=inst_idx,
                            ),
                            image_id=image_id,
                            class_key=class_key,
                            ann_type=AnnType.POINT,
                            geometry=pt_geom,
                            role="instance",
                            source=SourceType.ORIGINAL,
                            instance_index=inst_idx,
                        )

                        if tile_boxes is not None and local_idx < len(tile_boxes):
                            x1, y1, x2, y2 = tile_boxes[local_idx]
                            hbb_geom = HBB(
                                x=float(x1) + offset_x,
                                y=float(y1) + offset_y,
                                w=float(x2 - x1),
                                h=float(y2 - y1),
                            )
                            yield InstanceAnnotationRecord(
                                ann_id=make_ann_id(
                                    image_id=image_id,
                                    class_key=class_key,
                                    ann_type=AnnType.HBB,
                                    geometry=hbb_geom,
                                    source=SourceType.GENERATED,
                                    instance_index=inst_idx,
                                ),
                                image_id=image_id,
                                class_key=class_key,
                                ann_type=AnnType.HBB,
                                geometry=hbb_geom,
                                role="hbb",
                                source=SourceType.GENERATED,
                                instance_index=inst_idx,
                            )

                        inst_idx += 1
